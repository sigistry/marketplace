#!/usr/bin/env node
/*
 * Sigistry skills index.
 *
 * Walks every registry-hosted plugin's skills/<name>/SKILL.md, reads its
 * frontmatter, joins the parent plugin's verification status from
 * verified.json, and writes .claude-plugin/skills.json - the data source for
 * the sigistry.com/skills catalog and (later) MCP search_skills.
 *
 * Pure Node, no dependencies, static read only.
 * Usage: node scripts/generate-skills-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(p, 'utf8');
const exists = (p) => fs.existsSync(p);

/** Same YAML-ish frontmatter parser as verify-plugins.mjs (keep in sync). */
function frontmatter(md) {
  const m = md.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const out = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (kv) out[kv[1].toLowerCase()] = kv[2].trim();
  }
  return out;
}

const marketplace = JSON.parse(read(path.join(ROOT, '.claude-plugin', 'marketplace.json')));
const verified = JSON.parse(read(path.join(ROOT, '.claude-plugin', 'verified.json')));

const skills = [];
for (const entry of marketplace.plugins) {
  if (typeof entry.source !== 'string') continue; // external plugins indexed only when vendored/pinned
  const skillsDir = path.join(ROOT, entry.source.replace(/^\.\//, ''), 'skills');
  if (!exists(skillsDir)) continue;
  const v = verified.plugins?.[entry.name];
  for (const e of fs.readdirSync(skillsDir, { withFileTypes: true })) {
    if (!e.isDirectory()) continue;
    const sk = path.join(skillsDir, e.name, 'SKILL.md');
    if (!exists(sk)) continue;
    const fm = frontmatter(read(sk)) ?? {};
    skills.push({
      name: fm.name || e.name,
      description: fm.description || '',
      plugin: entry.name,
      pluginCategory: entry.category ?? null,
      status: v?.status ?? 'unknown',
      verifiedDate: v?.date ?? null,
    });
  }
}

skills.sort((a, b) => a.name.localeCompare(b.name));

const out = {
  $comment: 'Generated by scripts/generate-skills-index.mjs. Data source for sigistry.com/skills. Do not edit by hand.',
  methodologyUrl: 'https://sigistry.com/skill-verification',
  generated: new Date().toISOString(),
  count: skills.length,
  skills,
};

fs.writeFileSync(path.join(ROOT, '.claude-plugin', 'skills.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`${skills.length} skills across ${new Set(skills.map((s) => s.plugin)).size} plugins. Wrote .claude-plugin/skills.json`);
